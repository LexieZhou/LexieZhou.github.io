/** Decodes LAND_MASK into a Uint8Array of 0/1, one entry per grid cell. */
export function decodeLandMask() {
  const bytes = atob(LAND_MASK)
  const cells = new Uint8Array(COLS * ROWS)
  for (let i = 0; i < cells.length; i++) {
    cells[i] = (bytes.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1
  }
  return cells
}

/** Projects a lat/lon onto the plate as fractions of its width and height. */
export function project(lat, lon) {
  return {
    x: (lon + 180) / 360,
    y: (LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM),
  }
}
